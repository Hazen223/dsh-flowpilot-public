/**
 * FlowPilot client bundler.
 *
 * The Harness web loader expects one browser artifact that registers a lazy
 * factory whose id equals the package name. We author the client half as
 * several plain-JS fragments (each one is a sequence of statements, not a
 * module) and concatenate them inside that factory, in this order:
 *
 *   10-util.js        shared constants + pure helpers + i18n table
 *   20-store.js       reactive store over /flowpilot/api
 *   25-primitives.js  UI primitives           (ui-shell)
 *   30-shell.js       three-column workbench  (ui-shell)
 *   40-flow.js        node canvas + detail    (ui-flow)
 *   50-views.js       today/weekly/handoff/settings + dialogs (ui-views)
 *   60-quick.js       overlay dock / sidebar glyph / settings page
 *   70-css.js         aggregates every CSS_* constant
 *   80-apply.js       slot registrations + locale registration
 *
 * Cross-file references are therefore limited to `function` declarations
 * (hoisted) and values read at render time. `node build-client.mjs` writes
 * ./client.js; never edit client.js by hand.
 */
import { readFile, writeFile, stat } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = dirname(fileURLToPath(import.meta.url))
const SRC = join(root, 'src', 'client')
const OUT = join(root, 'client.js')

const FILES = [
  '10-util.js',
  '20-store.js',
  '25-primitives.js',
  '30-shell.js',
  '40-flow.js',
  '45-ai.js',
  '50-views.js',
  '55-sync.js',
  '57-update.js',
  '60-quick.js',
  '70-css.js',
  '80-apply.js',
]

const PKG = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))

const problems = []
const chunks = []

for (const name of FILES) {
  const path = join(SRC, name)
  let text
  try {
    text = await readFile(path, 'utf8')
  } catch {
    problems.push(`missing source file: src/client/${name}`)
    continue
  }
  const lines = text.split('\n')
  lines.forEach((line, index) => {
    if (/^\s*(import|export)\s/.test(line) || /^\s*import\s*\(/.test(line)) {
      problems.push(`src/client/${name}:${index + 1}: ES module syntax is not allowed in a client fragment`)
    }
    if (/require\(\s*['"]@deepseek-ai\//.test(line)) {
      problems.push(`src/client/${name}:${index + 1}: requiring a Harness client package is not allowed`)
    }
    if (/document\.body\s*\.\s*(append|insertBefore)/.test(line)) {
      problems.push(`src/client/${name}:${index + 1}: appending to document.body is not allowed`)
    }
  })
  chunks.push(`/* ---------- src/client/${name} ---------- */\n${text.trim()}\n`)
}

if (problems.length > 0) {
  console.error('build-client: refusing to emit\n' + problems.map((p) => '  - ' + p).join('\n'))
  process.exit(1)
}

const indent = (text) => text.split('\n').map((line) => (line.trim() === '' ? '' : '    ' + line)).join('\n')

const banner = `/**
 * FlowPilot ${PKG.version} — client half (generated by build-client.mjs, do not edit).
 * Registers a lazy factory whose id equals the package name; the Harness web
 * module table supplies React, so no duplicate React is bundled here.
 */`

const output = `${banner}
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PKG.name)},
  factory(require) {
    'use strict';
    const React = require('react');
    const h = React.createElement;
    const { useState, useEffect, useLayoutEffect, useRef, useMemo, useCallback, useReducer } = React;
    const FP_BUILD = ${JSON.stringify(new Date().toISOString())};

${indent(chunks.join('\n'))}

    return {
      inject: FP_CLIENT_INJECT,
      apply: FP_CLIENT_APPLY,
      version: FP_BUILD,
      // 离线冒烟测试入口（tests/client-smoke.mjs 使用；运行时不读取）。
      __test: {
        store: fpStore,
        seed: (payload) => fpStore.__seed(payload),
        utils: { fpNextNode, fpAccentCss, fpApplyAccentHue, fpAccentHueRead },
        components: {
          FpRoot, QuickDock, FpSettingsPage, FpSidebarGlyph,
          FlowView, NodeDetail, FlowNodeCard, AiPrdDialog, FpSyncPanel, FpUpdatePanel, FpUpdateBadge,
          TodayView, WeeklyView, HandoffView, SettingsView, ProjectOverview, FpHeaderChip,
          ProjectCreateDialog, LineEditDialog, LinkDialog, ScheduleDialog, ReasonDialog, NodeAddDialog,
        },
      },
    };
  },
});
`

await writeFile(OUT, output, 'utf8')
const { size } = await stat(OUT)
const lineCount = output.split('\n').length
console.log(`build-client: wrote client.js (${(size / 1024).toFixed(1)} KiB, ${lineCount} lines) from ${FILES.length} fragments`)
